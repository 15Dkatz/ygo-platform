def skin(id_: str, glob: str, duel: str, extra: str, band: str, edge: str, lines: float = .25) -> str:
    s = f':root[data-skin="{id_}"]:not(#_)'
    return f"""
/* ================= {id_} ================= */
{s} {{{glob}}}
{s} .duel-page {{{duel}}}
{extra.replace("{s}", s)}
{PHASE.format(s=s, band=band, edge=edge, lines=lines)}"""


