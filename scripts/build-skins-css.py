def svg(body: str, w: int = 240, h: int = 240) -> str:
    s = f"<svg xmlns='http://www.w3.org/2000/svg' width='{w}' height='{h}'>{body}</svg>"
    return 'url("data:image/svg+xml,' + quote(s, safe="/:=' ,.()-") + '")'


def noise(freq: str, octaves: int, rgb: tuple[float, float, float], alpha: float, seed: int = 1, w: int = 240, h: int = 240, kind: str = "fractalNoise") -> str:
    r, g, b = rgb
    return svg(
        f"<filter id='n'><feTurbulence type='{kind}' baseFrequency='{freq}' numOctaves='{octaves}' seed='{seed}' stitchTiles='stitch'/>"
        f"<feColorMatrix values='0 0 0 0 {r} 0 0 0 0 {g} 0 0 0 0 {b} {alpha} 0 0 0 0'/></filter>"
        f"<rect width='100%' height='100%' filter='url(#n)'/>", w, h)


def lit(freq: str, octaves: int, scale: float, elev: int, seed: int = 4, w: int = 300, h: int = 300) -> str:
    """Bumpy relief (grey, lit from the top left): multiply it over a base colour."""
    return svg(
        f"<filter id='s' x='0' y='0' width='100%' height='100%'><feTurbulence type='fractalNoise' baseFrequency='{freq}' numOctaves='{octaves}' seed='{seed}' stitchTiles='stitch' result='t'/>"
        f"<feDiffuseLighting in='t' lighting-color='#fff' surfaceScale='{scale}'><feDistantLight azimuth='225' elevation='{elev}'/></feDiffuseLighting></filter>"
        f"<rect width='100%' height='100%' filter='url(#s)'/>", w, h)


