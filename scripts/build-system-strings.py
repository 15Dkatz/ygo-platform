"""Generates src/worker/duel/engine/systemStrings.ts: EDOPro's system strings (the texts the rules engine
names choices with: "Normal Summon", "Activate this card's effect now?", "Add the card(s) to your hand"...).

Source: ProjectIgnis/Distribution config/strings.conf. Refresh with:

    curl -sSfL -o strings.conf https://raw.githubusercontent.com/ProjectIgnis/Distribution/master/config/strings.conf
    python scripts/build-system-strings.py strings.conf
"""
import json
import re
import sys
from pathlib import Path

src = Path(sys.argv[1] if len(sys.argv) > 1 else "strings.conf").read_text(encoding="utf-8")
system: dict[int, str] = {}
for line in src.splitlines():
    m = re.match(r"^!system\s+(\d+)\s+(.*)$", line.strip())
    if m:
        system[int(m.group(1))] = m.group(2).strip()

body = ",\n".join(f"  {k}: {json.dumps(v, ensure_ascii=False)}" for k, v in sorted(system.items()))
out = f"""// GENERATED by scripts/build-system-strings.py from EDOPro's strings.conf: edit that script, not this file.
// The rules engine's system strings ({len(system)}), by id.
export const SYSTEM_STRINGS: Record<number, string> = {{
{body},
}};
"""
Path("src/worker/duel/engine/systemStrings.ts").write_text(out, encoding="utf-8")
print(f"wrote {len(system)} system strings")
